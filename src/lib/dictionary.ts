/**
 * Resolves a bilingual catalog field using the store's active locale:
 * Arabic (`ar`) prefers the primary field, English (`en`) prefers `english`,
 * gracefully falling back to whichever language is populated.
 */
export function pickLocalized(
  locale: Locale,
  primary: string | null | undefined,
  english?: string | null | undefined
): string {
  const arValue = primary?.trim() ?? "";
  const enValue = english?.trim() ?? "";
  if (locale === "en") return enValue || arValue;
  return arValue || enValue;
}

/** Matches either English or Arabic names for bespoke Custom Color options. */
export function isCustomColorName(
  primary?: string | null,
  english?: string | null
): boolean {
  const values = [primary, english]
    .map((v) => v?.trim().toLowerCase() ?? "")
    .filter(Boolean);
  return values.some((v) => v === "custom color" || v === "لون مخصص");
}
